#!/usr/bin/env python3
"""Extract hp2wsfix's per-element FrontEnd/HUD layout table (the body of sub_59B840_hook_2 in
hp2wsfix/dllmain.cpp, MIT, (c) 2019 Lovro Plese) into a C include for runtime/hp2_widescreen.c.

  gen_ws_hud.py hp2wsfix/dllmain.cpp OUT.inc

The body only uses strcmp/strrchr on the element name and plain arithmetic on the mBorders
struct, so it compiles as C unchanged; the include is regenerated on every build, never edited."""
import sys
src = open(sys.argv[1], encoding="utf-8-sig").read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith("int __stdcall sub_59B840_hook_2("))
call = next(i for i in range(start, len(src)) if "sub_59B840(thethis, key" in src[i])
end = next(i for i in range(call, len(src)) if src[i].strip() == "return retval;" and src[i + 1].strip() == "}")
body = src[call + 1:end]
for bad in ("_asm", "injector::", "->"):
    if any(bad in l and not l.strip().startswith("//") for l in body):
        raise SystemExit(f"unexpected construct {bad!r} in hook body")
with open(sys.argv[2], "w") as f:
    f.write("/* GENERATED by tools/gen_ws_hud.py from hp2wsfix/dllmain.cpp (MIT License,\n"
            " * Copyright (c) 2019 Lovro Plese). Do not edit. */\n")
    f.write("\n".join(body) + "\n")
print(f"hp2ws: HUD table {len(body)} lines -> {sys.argv[2]}")
